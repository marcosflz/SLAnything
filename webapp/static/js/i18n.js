export function t(text, vars = {}) {
  let value = lang === "en" ? (EN[text] || text) : text;
  Object.entries(vars).forEach(([key, replacement]) => {
    value = value.replaceAll(`{${key}}`, String(replacement));
  });
  return value;
}

export function locale() {
  return lang === "en" ? "en-US" : "es-ES";
}
