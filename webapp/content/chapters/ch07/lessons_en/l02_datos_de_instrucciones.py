"""Lesson 2 · Building an instruction dataset."""

from webapp.content.schema import (
    Lesson,
    callout,
    check,
    h2,
    keypoints,
    lead,
    p,
    table,
)

LESSON = Lesson(
    number=2,
    slug="datos-de-instrucciones",
    title="Building a dataset",
    summary=(
        "An instruction set is designed: every pair must be clear, correct, and diverse, "
        "and its provenance and licence must be explainable."
    ),
    minutes=10,
    objectives=(
        "Describe the structure of an instruction, input, and response pair.",
        "Apply quality and diversity criteria to a small collection.",
        "Recognise licence, privacy, and contamination risks.",
        "Justify the train, validation, and test split.",
    ),
    blocks=(
        lead(
            "An instruction dataset is not a pile of sentences: it is a collection of "
            "promises about how the model should behave. If a response is wrong, "
            "inconsistent, or leaks personal data, tuning will learn that too. Before "
            "training, read the data as if it were production code."
        ),
        p(
            "The book's set contains <strong>1,100 pairs</strong> in a JSON file of about "
            "204 KB. Each entry has three fields: <code>instruction</code>, which describes "
            "the task; <code>input</code>, an optional context that may be empty; and "
            "<code>output</code>, the desired response. One example asks for the correct "
            "spelling of “Ocassion” and answers “The correct spelling is 'Occasion.'”. "
            "Another needs no input: “What is an antonym of 'complicated'?” is answered "
            "directly. The template must know how to omit the input section when it adds "
            "nothing."
        ),
        h2("Anatomy of a pair"),
        table(
            ["Field", "Purpose", "Example"],
            [
                ["instruction", "Task being requested", "Fix the spelling."],
                ["input", "Optional context", "Ocassion"],
                ["output", "Reference response", "The correct spelling is 'Occasion.'"],
            ],
            caption="The three fields of a typical entry. The input may be empty.",
            note="The exact format varies between datasets; what matters is that the template stays consistent.",
        ),
        p(
            "The book splits the data into 85% training, 10% test, and 5% validation: 935, "
            "110, and 55 examples. Validation is used to watch the loss and detect overfitting "
            "during training; test is held back for the final evaluation. Mixing both uses "
            "means making decisions with information that should be invisible, and the metric "
            "stops being honest. On small sets, a single unusual row can move the average a "
            "great deal."
        ),
        h2("Quality, diversity, and licences"),
        p(
            "Quality starts with correctness: a bad response teaches an error. It continues "
            "with clarity: ambiguous instructions produce ambiguous targets. It ends with "
            "consistency: if two nearly identical examples receive incompatible answers, the "
            "model receives noise. A simple checklist —correct, relevant, self-contained, and "
            "in the requested language— catches many problems early. Record the checklist and "
            "the filter in the dataset card. Review duplicates, extreme "
            "lengths, formatting artefacts that leak into the text, and responses that do not "
            "answer the question. On a set "
            "of 1,100 pairs, a sampled manual review is feasible; on 52,002 entries such as "
            "the original Alpaca dataset, a more systematic filtering process is required."
        ),
        p(
            "Diversity prevents the model from learning a single script. A useful set mixes "
            "transformation tasks, open questions, extraction, summarisation, classification, "
            "and correction; it varies length and tone; it includes examples with and without "
            "context; and it covers different difficulty levels. It should also resemble the "
            "real requests expected in production, not only the tasks that are comfortable to "
            "write. If every response starts the same way, the model will learn that tic "
            "before it learns the task."
        ),
        p(
            "Provenance is part of quality. Before using a dataset, check its licence, the "
            "conditions of the source, and whether the responses were generated by another "
            "model whose terms restrict use. Also review personal data, copyrighted text, and "
            "examples that may contain bias. A file being published in a repository does not "
            "mean it can be used without restrictions. Document the version, date, and filter "
            "applied: without traceability, a result cannot be reproduced or audited."
        ),
        callout(
            "warning",
            "Contamination is trained too",
            "If a test question appears in the training set, evaluation measures memory, not "
            "generalisation. Split the sets before any data augmentation and check that they "
            "do not share near-identical instructions. The same care applies to public "
            "benchmarks used as references.",
        ),
        check(
            "Why should the test set not be used to decide when to stop training?",
            "Because those decisions leak test information into the model: you choose the "
            "configuration that scores best on test, and the final metric stops estimating "
            "performance on new data. Validation exists for that decision.",
        ),
        keypoints(
            [
                "Each pair has an instruction, an optional input, and a reference response.",
                "The template should omit the input section when it is empty.",
                "The book splits 935 / 55 / 110 examples (85 / 5 / 10%).",
                "Quality requires correct, clear, and consistent responses.",
                "Diversity of tasks and formats improves generalisation.",
                "Licences, privacy, and contamination are checked before training.",
            ]
        ),
    ),
    key_points=(
        "An instruction dataset is designed and audited, not merely downloaded.",
        "Instruction, optional input, and response form the training pair.",
        "Validation guides decisions; test is reserved for final evaluation.",
        "Quality, diversity, licence, and privacy are data requirements.",
    ),
)
